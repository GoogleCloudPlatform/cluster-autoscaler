// Package flexadvisor tests verification of FlexAdvisor Rank behavior in Big Unit Tests (BUTs).
//
// Verifying Sent Rank in Big Unit Tests:
//
// In the BUT framework, FakeFlexAdvisorClient implements flexadvisorapi.AdviceProvider
// (FetchCapacityGuidance) and follows the BUT design principle ("Configure State, Don't Mock Interactions" /
// "Verify State, Not Interactions") by matching configured CapacityGuidance rules (including .WithRank(rank))
// against the InstanceConfigs generated by Cluster Autoscaler rather than recording requests.
//
// FakeFlexAdvisorClient evaluates CapacityGuidance rules in order (first match wins) and defaults
// unmatched configs to DefaultZonalCapacity = 1000.
//
// Therefore:
//  1. To prove a higher-priority option was sent with Rank = R and is stocked out: we configure
//     fake.NewGuidance(mt).WithRank(R).WithCapacity(0) without a fallback rule for mt. If CA sent
//     Rank == R, it matches and gets 0 capacity (forcing fallback). If CA sent any other rank, the
//     rule would not match and mt would receive DefaultZonalCapacity (1000), causing CA to scale up
//     mt instead of falling back.
//  2. To prove the target priority option was sent with Rank = R and scales up: we configure
//     fake.NewGuidance(mt).WithRank(R).WithCapacity(10) followed by a catch-all
//     fake.NewGuidance(mt).WithCapacity(0). If CA sent Rank == R, it matches the first rule
//     (10 capacity) and scales up. If CA sent any other rank, it falls through to the second rule
//     (0 capacity) and fails to scale up.
